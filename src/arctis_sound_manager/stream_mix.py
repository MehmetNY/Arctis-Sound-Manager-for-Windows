"""Streamer mode: a second, independent mix of the channels for OBS to record.

Mirrors SteelSeries Sonar's "Stream" mode. The personal (headset) mix is left
alone; this one is Game + Chat + Media + Aux + the processed Mic, each with its
own volume and mute, delivered as a virtual stereo ``Audio/Source``
(``effect_output.sonar-stream-mix``) that OBS, or anything else, can record.

Qt-free on purpose: the daemon applies the gains, the GUI only edits the state
file and asks the daemon (via the setting) to do the plumbing. The graph itself
is generated by ``sonar_to_pipewire.generate_stream_mix_conf`` and linked by
``sonar_to_pipewire.ensure_stream_mix_links``.

Why the mix is independent of the headset mix: it taps the *monitor* of each
``Arctis_<Channel>`` sink. Those monitors default to ``monitor.channel-volumes
= false`` and carry their own mute, so they sit before the sink's volume/mute
and before ChatMix (which acts on the ``*_sink_out`` sink-inputs, downstream).
"""

from __future__ import annotations

import json
import logging
import os
from pathlib import Path

from arctis_sound_manager.constants import IS_WINDOWS

_log = logging.getLogger(__name__)

STREAM_MIX_INPUT_NODE = "effect_input.sonar-stream-mix"
STREAM_MIX_OUTPUT_NODE = "effect_output.sonar-stream-mix"

# Order is the mixer slot order: Gain 1..5 on both mixL and mixR.
STREAM_CHANNELS = ("game", "chat", "media", "aux", "mic")

STREAM_MIX_FILE = Path.home() / ".config" / "arctis_manager" / "stream_mix.json"


def _default_state() -> dict[str, dict]:
    return {ch: {"volume": 100, "muted": False} for ch in STREAM_CHANNELS}


def _clamp_volume(value) -> int:
    # bool is an int subclass: True would otherwise read as volume 1.
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return 100
    return max(0, min(100, int(round(value))))


def load_stream_mix() -> dict[str, dict]:
    """The saved per-channel state, with defaults for anything missing.

    Never raises: a missing, truncated or hand-edited file must not take the
    mixer (or the daemon's start-up) down with it — it just reads as defaults.
    """
    state = _default_state()
    try:
        raw = json.loads(STREAM_MIX_FILE.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return state
    if not isinstance(raw, dict):
        return state
    for ch in STREAM_CHANNELS:
        entry = raw.get(ch)
        if not isinstance(entry, dict):
            continue
        state[ch]["volume"] = _clamp_volume(entry.get("volume", 100))
        muted = entry.get("muted", False)
        state[ch]["muted"] = muted if isinstance(muted, bool) else False
    return state


def save_stream_mix_channel(channel: str, volume: int | None = None,
                            muted: bool | None = None) -> None:
    """Persist one channel's volume and/or mute; ``None`` leaves a field as is.

    Atomic (tmp + fsync + rename), like the other state files: the daemon and
    the GUI both read this and a torn write would read back as all defaults.
    """
    if channel not in STREAM_CHANNELS:
        _log.warning("save_stream_mix_channel: unknown channel %r", channel)
        return
    state = load_stream_mix()
    if volume is not None:
        state[channel]["volume"] = _clamp_volume(volume)
    if muted is not None:
        state[channel]["muted"] = bool(muted)
    path = STREAM_MIX_FILE
    tmp = path.with_name(path.name + ".tmp")
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(state, f, indent=2)
            f.flush()
            os.fsync(f.fileno())
        tmp.replace(path)
    except OSError as exc:
        _log.warning("could not save the stream mix state: %s", exc)
        try:
            tmp.unlink(missing_ok=True)
        except OSError:
            pass


def stream_gain(volume: int, muted: bool) -> float:
    """Linear gain for a 0-100 slider: cubic, like PulseAudio's volume sliders.

    A linear map would put most of the audible range in the first few percent
    of travel; the cube matches the feel of the personal mix's sliders.
    """
    if muted:
        return 0.0
    return (_clamp_volume(volume) / 100.0) ** 3


def stream_mix_controls(state: dict | None = None) -> dict[str, float]:
    """``{"mixL:Gain 1": …, "mixR:Gain 5": …}`` for *state* (default: saved)."""
    if state is None:
        state = load_stream_mix()
    controls: dict[str, float] = {}
    for slot, ch in enumerate(STREAM_CHANNELS, start=1):
        entry = state.get(ch) or {}
        gain = stream_gain(entry.get("volume", 100), bool(entry.get("muted", False)))
        controls[f"mixL:Gain {slot}"] = gain
        controls[f"mixR:Gain {slot}"] = gain
    return controls


def apply_stream_mix(state: dict | None = None) -> bool:
    """Push every gain to the running stream-mix node in ONE ``set-param``.

    Returns False when the node is not in the graph (streamer mode off, or the
    filter-chain still starting) — the watchdog re-applies once it appears.
    Never raises.

    On Windows there is no graph to push into: the audio engine (win/audio/)
    reads this state file itself, so all that is left to do is tell it to look
    now instead of at its next poll.
    """
    if IS_WINDOWS:
        try:
            from arctis_sound_manager.win.audio.bridge import shared_bridge
            shared_bridge().reload()
            return True
        except Exception as exc:                                 # noqa: BLE001
            _log.warning("apply_stream_mix failed: %r", exc)
            return False
    try:
        from arctis_sound_manager.pw_utils import set_filter_controls
        return bool(set_filter_controls(STREAM_MIX_INPUT_NODE,
                                        stream_mix_controls(state)))
    except Exception as exc:
        _log.warning("apply_stream_mix failed: %r", exc)
        return False
